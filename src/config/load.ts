import { existsSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { pathToFileURL } from "node:url";
import { resolveTheme, type Theme } from "../../composition/src/theme.ts";
import { fail } from "../core/errors.ts";
import { readJson } from "../core/json.ts";
import { programName } from "../core/program.ts";
import type { SpokenForm } from "../builder/captions.ts";
import { type MediaStore, vercelBlob } from "../release/blob.ts";
import type { ApprovalKind, LocalSansFont, OncueConfig, RedactRule } from "./config.ts";

export const CONFIG_FILES = ["oncue.config.ts", "oncue.config.mts", "oncue.config.js", "oncue.config.mjs", "oncue.config.json"];

/** A config with every default filled in. Paths are relative to the repo root. */
export interface ResolvedConfig {
  cli: { name: string; description: string };
  paths: {
    projects: string;
    catalog: string;
    public: string;
    media: string;
    registry: string;
    ledger: string;
    env: string;
    videoTemplate: string | null;
  };
  brandLabel: string;
  theme: Theme;
  localSans: LocalSansFont | null;
  composition: string | null;
  captions: { spoken: SpokenForm[] };
  narration: { envPrefix: string };
  metadata: {
    visibilities: string[];
    types: string[];
    approvals: Record<string, ApprovalKind>;
    summaryMax: number;
    unnumberedSeriesTags: boolean;
  };
  checks: { redact: RedactRule[]; scan: string[] };
  registry: { comment: string };
  ledger: { comment: string };
  site: { repo: string; snapshot: string } | null;
  mediaStore: MediaStore;
}

export function resolveConfig(c: OncueConfig = {}): ResolvedConfig {
  // How a repo with oncue as a dev dependency runs it; there's no global `oncue`.
  const name = c.cli?.name ?? "npx oncue";
  return {
    cli: { name, description: c.cli?.description ?? "Narrated developer videos. <video> is a folder under projects/ or a video id." },
    paths: {
      projects: c.paths?.projects ?? "projects",
      catalog: c.paths?.catalog ?? "catalog",
      public: c.paths?.public ?? "public",
      media: c.paths?.media ?? "dist/media",
      registry: c.paths?.registry ?? "registry.json",
      ledger: c.paths?.ledger ?? "versions.json",
      env: c.paths?.env ?? ".env",
      videoTemplate: c.paths?.videoTemplate ?? null,
    },
    brandLabel: c.brandLabel ?? "",
    theme: resolveTheme(c.theme),
    localSans: c.localSans ?? null,
    composition: c.composition ?? null,
    captions: { spoken: c.captions?.spoken ?? [] },
    narration: { envPrefix: c.narration?.envPrefix ?? "ONCUE" },
    metadata: {
      visibilities: c.metadata?.visibilities ?? ["preview", "public"],
      types: c.metadata?.types ?? ["explainer", "walkthrough"],
      approvals: c.metadata?.approvals ?? {},
      summaryMax: c.metadata?.summaryMax ?? 160,
      unnumberedSeriesTags: c.metadata?.unnumberedSeriesTags ?? false,
    },
    checks: { redact: c.checks?.redact ?? [], scan: c.checks?.scan ?? ["catalog"] },
    registry: {
      comment:
        c.registry?.comment ??
        `Generated by \`${name} registry\` from the projects' video.json and the catalog. Don't edit by hand. ` +
          `Media changes only with \`${name} registry --accept <id>\`.`,
    },
    ledger: {
      comment: c.ledger?.comment ?? `Every accepted render of every video, appended by \`${name} registry --accept\`. Don't edit by hand.`,
    },
    site: c.site ?? null,
    mediaStore: c.mediaStore ?? vercelBlob,
  };
}

/** The nearest directory at or above `from` with an oncue config file. */
export function findRoot(from: string = process.cwd()): string | null {
  let d = resolve(from);
  for (;;) {
    if (CONFIG_FILES.some((f) => existsSync(join(d, f)))) return d;
    const up = dirname(d);
    if (up === d) return null;
    d = up;
  }
}

/** The config in `root` (TypeScript configs run on Node's type stripping). */
export async function loadConfig(root: string): Promise<OncueConfig> {
  const file = CONFIG_FILES.map((f) => join(root, f)).find((f) => existsSync(f));
  if (!file) fail(`no oncue config in ${root}. Run \`${programName()} init\` to create one.`);
  if (file.endsWith(".json")) return readJson<OncueConfig>(file);
  const mod = (await import(pathToFileURL(file).href)) as { default?: OncueConfig };
  if (!mod.default || typeof mod.default !== "object") fail(`${file}: the default export must be defineConfig({...})`);
  return mod.default;
}
